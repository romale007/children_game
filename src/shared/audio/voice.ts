import { Howl } from 'howler'
import { speak, stopSpeech } from './speech'

type Sound = { howl: Howl; failed: boolean }

// Every sound of every game, so starting a phrase (or leaving a game) silences all of them.
const allSounds = new Set<Sound>()
// The sound the current sequence is waiting on, and what to do if it fails to load.
let waiting: { sound: Sound; fallback: () => void } | undefined
// Bumped on every say() so callbacks from an interrupted sequence do nothing.
let generation = 0

export function stopAudio() {
  generation++
  waiting = undefined
  for (const { howl } of allSounds) {
    howl.off('end')
    howl.stop()
  }
  stopSpeech()
}

/**
 * Voice-over for one game: phrase id → text, with `<audioDir>/<id>.mp3` generated by
 * scripts/generate_audio.py. Missing or broken files are spoken by the browser voice instead.
 */
export function createVoice<Phrases extends Record<string, string>>(audioDir: string, phrases: Phrases) {
  type PhraseId = keyof Phrases & string
  const sounds = new Map<PhraseId, Sound>()

  function sound(id: PhraseId) {
    let entry = sounds.get(id)
    if (!entry) {
      const created: Sound = {
        failed: false,
        howl: new Howl({
          src: [`${audioDir}/${id}.mp3`],
          onloaderror: () => {
            // Howler keeps a failed sound in the 'loading' state, so failures are tracked here.
            created.failed = true
            if (waiting?.sound === created) waiting.fallback()
          },
        }),
      }
      entry = created
      sounds.set(id, entry)
      allSounds.add(entry)
    }
    return entry
  }

  /** Fetches every phrase in the background. */
  function preload() {
    for (const id of Object.keys(phrases) as PhraseId[]) sound(id)
  }

  /** Plays the phrases one after another, interrupting whatever is playing now. */
  function say(...ids: PhraseId[]) {
    sayThen(ids)
  }

  /** Like say(), then calls onDone when the last phrase ends. An interrupted sequence never calls it. */
  function sayThen(ids: PhraseId[], onDone?: () => void) {
    stopAudio()
    const current = generation
    const done = () => {
      if (current === generation) onDone?.()
    }

    const step = (i: number) => {
      if (current !== generation) return
      if (i >= ids.length) return done()
      const entry = sound(ids[i])
      // Speak the rest of the sequence with the browser voice if this file is unavailable.
      const fallback = () => {
        if (current === generation) speak(ids.slice(i).map((rest) => phrases[rest]).join(' '), done)
      }
      if (entry.failed) return fallback()
      waiting = { sound: entry, fallback }
      entry.howl.once('end', () => step(i + 1))
      entry.howl.play()
    }
    step(0)
  }

  return { say, sayThen, preload }
}
